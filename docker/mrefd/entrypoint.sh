#!/bin/bash
# =============================================================================
# mrefd container entrypoint.
# Renders /etc/mrefd/mrefd.cfg from the MREFD_* environment variables, verifies
# the live-editable list files exist, and execs mrefd.
# =============================================================================
set -euo pipefail

CFG=/etc/mrefd/mrefd.cfg

die() { echo "entrypoint: ERROR: $*" >&2; exit 1; }
note() { echo "entrypoint: $*" >&2; }

# ---- required fields --------------------------------------------------------
: "${MREFD_CALLSIGN:?MREFD_CALLSIGN is required (e.g. M17-XYZ)}"
: "${MREFD_MODULES:?MREFD_MODULES is required (e.g. BCD)}"
: "${MREFD_COUNTRY:?MREFD_COUNTRY is required (ISO-3166-1 alpha-2, e.g. US)}"
: "${MREFD_EMAIL:?MREFD_EMAIL is required}"
: "${MREFD_DASHBOARD_URL:?MREFD_DASHBOARD_URL is required}"

[[ "$MREFD_CALLSIGN" =~ ^M17-[A-Z0-9]{3}$ ]] || \
    die "MREFD_CALLSIGN must be 'M17-' followed by 3 A-Z/0-9 chars (got '$MREFD_CALLSIGN')"
[[ "$MREFD_MODULES" =~ ^[A-Z]+$ ]] || \
    die "MREFD_MODULES must be uppercase A-Z letters only (got '$MREFD_MODULES')"

# ---- defaults ---------------------------------------------------------------
MREFD_PORT="${MREFD_PORT:-17000}"
MREFD_IPV4_BIND="${MREFD_IPV4_BIND-0.0.0.0}"
MREFD_IPV6_BIND="${MREFD_IPV6_BIND-::}"
MREFD_LISTEN_ONLY_ALLOW_ENCRYPT="${MREFD_LISTEN_ONLY_ALLOW_ENCRYPT:-false}"
MREFD_DHT_ENABLED="${MREFD_DHT_ENABLED:-false}"
MREFD_BOOTSTRAP="${MREFD_BOOTSTRAP:-xrf757.openquad.net}"

# ---- render mrefd.cfg -------------------------------------------------------
{
    echo "# Generated by entrypoint.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# Do not edit inside the container - edit .env and restart the service."
    echo
    echo "Callsign = ${MREFD_CALLSIGN}"
    echo "Modules = ${MREFD_MODULES}"
    if [[ -n "${MREFD_ENCRYPTION_ALLOWED:-}" ]]; then
        echo "EncryptionAllowed = ${MREFD_ENCRYPTION_ALLOWED}"
    fi
    echo "ListenOnlyAllowEncrypt = ${MREFD_LISTEN_ONLY_ALLOW_ENCRYPT}"
    echo

    if [[ -n "${MREFD_IPV4_BIND}" ]]; then
        echo "IPv4BindAddr = ${MREFD_IPV4_BIND}"
    fi
    if [[ -n "${MREFD_IPV6_BIND}" ]]; then
        echo "IPv6BindAddr = ${MREFD_IPV6_BIND}"
    fi
    if [[ -z "${MREFD_IPV4_BIND}" && -z "${MREFD_IPV6_BIND}" ]]; then
        die "at least one of MREFD_IPV4_BIND or MREFD_IPV6_BIND must be set"
    fi
    echo "Port = ${MREFD_PORT}"
    echo

    echo "PidPath = /var/run/mrefd/mrefd.pid"
    echo "JsonPath = /var/log/mrefd/mrefd.json"
    echo "WhitelistPath = /etc/mrefd/mrefd.whitelist"
    echo "BlacklistPath = /etc/mrefd/mrefd.blacklist"
    echo "InterlinkPath = /etc/mrefd/mrefd.interlink"
    echo

    if [[ "${MREFD_DHT_ENABLED}" == "true" ]]; then
        [[ -n "${MREFD_IPV4_EXT:-}" ]] && echo "IPv4ExtAddr = ${MREFD_IPV4_EXT}"
        [[ -n "${MREFD_IPV6_EXT:-}" ]] && echo "IPv6ExtAddr = ${MREFD_IPV6_EXT}"
        echo "DashboardURL = ${MREFD_DASHBOARD_URL}"
        echo "EmailAddr = ${MREFD_EMAIL}"
        echo "Bootstrap = ${MREFD_BOOTSTRAP}"
        echo "DHTSavePath = /var/lib/mrefd/mrefd.dht.bin"
        echo "Country = ${MREFD_COUNTRY}"
        if [[ -n "${MREFD_SPONSOR:-}" ]]; then
            [[ "${MREFD_SPONSOR}" == *"="* ]] && \
                die "MREFD_SPONSOR must not contain '=' (got '${MREFD_SPONSOR}')"
            echo "Sponsor = ${MREFD_SPONSOR}"
        fi
    fi
} > "$CFG"

# ---- ensure list files exist ------------------------------------------------
# mrefd requires whitelist/blacklist/interlink files to exist even if empty.
# Users bind-mount /etc/mrefd/config-in on top of individual files; if the
# mounts are missing (fresh deploy), fall back to empty defaults.
for f in mrefd.whitelist mrefd.blacklist mrefd.interlink; do
    if [[ ! -f "/etc/mrefd/${f}" ]]; then
        note "creating empty ${f} (no host mount provided)"
        : > "/etc/mrefd/${f}"
    fi
done

# ---- start mrefd + Bonjour advertiser --------------------------------------
# mrefd is the primary process; if it exits, the container exits with its
# code. The Bonjour advertiser starts 10 seconds later so that mrefd is
# already bound and accepting traffic by the time the service becomes
# discoverable on the LAN. Both children receive forwarded SIGTERM/SIGINT.

MREFD_PID=""
ADV_PID=""
shutdown() {
    note "shutting down"
    [[ -n "$MREFD_PID" ]] && kill -TERM "$MREFD_PID" 2>/dev/null || true
    [[ -n "$ADV_PID"   ]] && kill -TERM "$ADV_PID"   2>/dev/null || true
    wait 2>/dev/null || true
    exit 0
}
trap shutdown TERM INT

note "starting mrefd as ${MREFD_CALLSIGN} on modules ${MREFD_MODULES}, UDP ${MREFD_PORT}"
/usr/local/bin/mrefd "$CFG" &
MREFD_PID=$!

# ---- advertiser (optional; on by default) ----------------------------------
if [[ "${MREFD_ADVERTISE_ENABLED:-true}" == "true" ]]; then
    (
        # Wait for mrefd to be up and listening. Keeps the mDNS announcement
        # from telling clients "here I am!" before we can actually serve.
        sleep 10

        # Derive slug and designator from callsign.
        # MREFD_CALLSIGN = "M17-020" -> designator=020, slug=m17-020
        _designator="${MREFD_CALLSIGN#M17-}"
        _slug=$(printf '%s' "$MREFD_CALLSIGN" | tr '[:upper:]' '[:lower:]')

        # Comma-separate the module strings so m17-advertise's --modules /
        # --encrypted flags see the same shape they'd get from CLI use.
        _split() { printf '%s' "$1" | sed -e 's/./&,/g' -e 's/,$//'; }

        ADV=(--designator "$_designator" --slug "$_slug"
             --port "$MREFD_PORT"
             --modules "$(_split "$MREFD_MODULES")")

        [[ -n "${MREFD_COUNTRY:-}"              ]] && ADV+=(--country      "$MREFD_COUNTRY")
        [[ -n "${MREFD_SPONSOR:-}"              ]] && ADV+=(--sponsor      "$MREFD_SPONSOR")
        [[ -n "${MREFD_DASHBOARD_URL:-}"        ]] && ADV+=(--url          "$MREFD_DASHBOARD_URL")
        [[ -n "${MREFD_ENCRYPTION_ALLOWED:-}"   ]] && ADV+=(--encrypted    "$(_split "$MREFD_ENCRYPTION_ALLOWED")")
        [[ -n "${MREFD_IPV4_EXT:-}"             ]] && ADV+=(--ipv4         "$MREFD_IPV4_EXT")
        [[ -n "${MREFD_IPV6_EXT:-}"             ]] && ADV+=(--ipv6         "$MREFD_IPV6_EXT")
        [[ -n "${MREFD_ADVERTISE_NAME:-}"       ]] && ADV+=(--name         "$MREFD_ADVERTISE_NAME")
        [[ -n "${MREFD_ADVERTISE_DESCRIPTION:-}" ]] && ADV+=(--description  "$MREFD_ADVERTISE_DESCRIPTION")
        [[ -n "${MREFD_ADVERTISE_NETWORK_TYPE:-}" ]] && ADV+=(--network-type "$MREFD_ADVERTISE_NETWORK_TYPE")

        # If a bind-mounted site.json is present, use it as base; per-field
        # env vars still overlay on top (m17-advertise flag semantics).
        SITE="${MREFD_ADVERTISE_CONFIG:-/etc/mrefd/site.json}"
        if [[ -f "$SITE" ]]; then
            ADV=(--config "$SITE" "${ADV[@]}")
        fi

        note "starting Bonjour advertiser for ${_slug}"
        exec /usr/local/bin/m17-advertise "${ADV[@]}"
    ) &
    ADV_PID=$!
else
    note "advertiser disabled (MREFD_ADVERTISE_ENABLED=false)"
fi

# Wait for mrefd; the advertiser is best-effort and its exit is not fatal.
wait "$MREFD_PID"
MREFD_RC=$?
[[ -n "$ADV_PID" ]] && kill -TERM "$ADV_PID" 2>/dev/null || true
wait 2>/dev/null || true
exit "$MREFD_RC"
